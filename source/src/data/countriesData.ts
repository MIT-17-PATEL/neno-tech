/**
 * Returns state list for a given country ISO code, or null if fallback free-text should be used.
 */
export function getStatesForCountry(countryCode: string): string[] | null {
    if (!countryCode) return null;
    const states = COUNTRY_STATES[countryCode.toUpperCase()];
    return states && states.length > 0 ? states : null;
}

/**
 * Finds CountryOption by name (case-insensitive)
 */
export function getCountryByName(name: string): CountryOption | undefined {
    if (!name) return undefined;
    const lower = name.trim().toLowerCase();
    return COUNTRIES.find((c) => c.name.toLowerCase() === lower);
}

/**
 * Finds CountryOption by 2-letter ISO code (case-insensitive)
 */
export function getCountryByCode(code: string): CountryOption | undefined {
    if (!code) return undefined;
    const upper = code.trim().toUpperCase();
    return COUNTRIES.find((c) => c.code.toUpperCase() === upper);
}
